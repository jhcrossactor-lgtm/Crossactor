# -*- coding: utf-8 -*-
"""add_markers.py と hunt.py が共有する正規化。

両者がここを使うことで「hunt.py では見つかるのに add_markers.py では当たらない」
（およびその逆）を無くす。片方だけを直すな。必ずこのファイルを直す。

NFKC は使わない。add_markers.py は PDF の文字を1文字ずつ正規化して bbox と
対応付けるため、1文字が2文字以上に展開される変換（㍉→ミリ）をかけると
ハイライトの座標がズレる。幅そろえは 1文字→1文字 のものだけに限る。
"""
import re

# 音声由来の表記ゆれ。複数文字のキーなので、1文字ずつ正規化される PDF 側では
# 発火せず、marks_*.txt の文言（=クエリ）側でのみ効く。それで狙いどおり：
# 「脅迫」と書かれたクエリが、紙面の「強迫」に当たる。
VARIANTS = {"脅迫": "強迫", "帰す": "帰す", "関わらず": "かかわらず", "合わせて": "併せて"}

# 幅ちがいを吸収する。すべて 1文字→1文字。
# 「5%」と「５％」、「1か月」と「1ヶ月」が当たらない問題への対処。
WIDTH = str.maketrans({
    **{chr(0xFF10 + i): chr(0x30 + i) for i in range(10)},      # ０-９ → 0-9
    **{chr(0xFF21 + i): chr(0x41 + i) for i in range(26)},      # Ａ-Ｚ → A-Z
    **{chr(0xFF41 + i): chr(0x61 + i) for i in range(26)},      # ａ-ｚ → a-z
    "％": "%", "＋": "+", "／": "/", "＝": "=", "＆": "&", "＠": "@",
    "ヶ": "か", "ヵ": "か",
})

# 落とす記号。空白・約物に加えて、marks_*.txt に混ざりうるマークダウン記号
# （* _ | #）も落とす。LLM の回答をそのまま貼ると **太字** が紛れ込み、
# 落とさないと確実に照合を外す。
DROP = re.compile(r"[\s　、。，．,.「」『』（）()・:：;；…\-－―ー〜～⇨→*_|#]")


def norm(s):
    for a, b in VARIANTS.items():
        s = s.replace(a, b)
    return DROP.sub("", s.translate(WIDTH))
